#!/usr/bin/env python3
"""Generate bounded C-locale data from the pinned BSD-licensed upstream table."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
source=(ROOT/'assets/darwin/rune/table.c').read_text()
assert hashlib.sha256(source.encode()).hexdigest()=='2e99278105bb2e3f4ae38eaebabe8333c2c28dbc3d815fd15fb18c055ac5cc34'
clean=re.sub(r'/\*.*?\*/','',source,flags=re.S)
body=clean[clean.index('_RuneLocale _DefaultRuneLocale'):]
body=body[body.index('= {')+3:body.index('\n};')]
arrays=re.findall(r'\{([^{}]+)\}',body)
assert len(arrays)==3
# Public Darwin ctype ABI mask values. No hosted locale-dependent predicates.
masks=dict(A=0x100,C=0x200,D=0x400,G=0x800,L=0x1000,P=0x2000,S=0x4000,U=0x8000,
           X=0x10000,B=0x20000,R=0x40000,I=0x80000,T=0x100000,Q=0x200000,
           SW0=0x20000000,SW1=0x40000000,SW2=0x80000000,SW3=0xc0000000)
values=[]
for index,array in enumerate(arrays):
    result=[]
    for item in array.split(','):
        if not item.strip():continue
        value=0
        for token in item.split('|'):
            token=token.strip()
            if token.startswith('_CTYPE_'):value|=masks[token[7:]]
            elif re.fullmatch(r"'[A-Za-z]'",token):value|=ord(token[1])
            else:
                assert re.fullmatch(r'(?:0x[0-9a-fA-F]+|\d+)',token),token
                value|=int(token,0)
        assert 0<=value<1<<32
        result.append(value)
    assert len(result)==(128 if index==0 else 256),len(result)
    # The C initializer leaves classes128..255 implicitly zero.
    if index==0:result += [0]*128
    values+=result
raw=b''.join(value.to_bytes(4,'little') for value in values)
words=[int.from_bytes(raw[i:i+8],'little',signed=True) for i in range(0,len(raw),8)]
result='''// BSD-3-Clause data derived from Apple's Libc table.c.
// Copyright (c) 1993 The Regents of the University of California.
// Full permission notice: assets/darwin/rune/LICENSE-BSD.
// Generated by scripts/build-darwin-rune.py. No host locale/runtime dependency.
package space.personality.darwin
var darwin-rune-cache:[Int]=[WORDS]
const DARWIN-RUNE-OBJECT-BYTES=3208
const DARWIN-RUNE-CURRENT-OFFSET=3216
fn darwin-rune-populate(buffer:Int,bytes:Int,guest-base:Int)->Int{
  if buffer<=0 || bytes!=4096 || guest-base<=0 || (guest-base&4095)!=0{return -22;}
  let i=0;while i<4096{store64(buffer+i,0);i+=8;}
  store64(buffer,0x4167614d656e7552); // RuneMagA, little endian
  store32(buffer+8,0x454e4f4e); // NONE
  store32(buffer+56,65533);
  i=0;while i<768{
    let word=darwin-rune-cache[i/2];let shift=(i%2)*32;
    store32(buffer+60+i*4,(word>>shift)&0xffffffff);i+=1;
  }
  store64(buffer+DARWIN-RUNE-CURRENT-OFFSET,guest-base);
  return 0;
}
'''.replace('WORDS',','.join(map(str,words)))
path=ROOT/'components/darwin-rune.in'
if a.check:assert path.read_text()==result
else:path.write_text(result)
receipt=dict(upstream='apple-oss-distributions/Libc',revision='71bbe350ab79eef58113991d817ccc6165061a64',
             file='locale/FreeBSD/table.c',source_sha256=hashlib.sha256(source.encode()).hexdigest(),
             license='BSD-3-Clause (original numbered conditions 1,2,4)',
             cache_words=768,cache_sha256=hashlib.sha256(raw).hexdigest(),
             ABI_references=['include/runetype.h','include/_ctype.h'],
             scope='Exact cached C-locale arrays only; no hosted runtime or Rosemary code')
receipt_path=ROOT/'assets/darwin/rune/provenance.json';text=json.dumps(receipt,indent=2)+'\n'
if a.check:assert receipt_path.read_text()==text
else:receipt_path.write_text(text)
print('PASS768 pinned Darwin rune cache words; sha256='+receipt['cache_sha256'])
