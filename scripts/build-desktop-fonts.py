#!/usr/bin/env python3
"""Bake bounded desktop coverage using Pillow/FreeType; no font parser at runtime."""
import argparse
import hashlib
import json
from pathlib import Path
import re

from PIL import Image, ImageDraw, ImageFont, __version__

ROOT = Path(__file__).resolve().parents[1]
PINNED = {
    'DejaVuSans.ttf': '57f73e11f51999432bf7ab22ce55b6f945d5eca1bf824404cfa9ec2e3718c84e',
    'DejaVuSansMono.ttf': '54bf827eb99404e8f430c330ad30f063334f637eba0109b6a18d4f566a8e9dd8',
}


def generate(font_dir):
    advances = {int(ch): int(adv) for ch, adv in re.findall(
        r'fb-font-sans-set\((\d+), (\d+),', (ROOT/'components/font.in').read_text())}
    lines = ['package space.display', '', '// Generated by scripts/build-desktop-fonts.py.',
             '// DejaVu raster assets: assets/fonts/desktop/DejaVu-LICENSE.txt.',
             '// ASCII only; existing layout/cell metrics unchanged.',
             'var desktop-font-mono24: Int = 0',
             'var desktop-font-sans24: Int = 0', '']
    receipt = {'pillow': __version__, 'coverage': 'ASCII 32..126',
               'encoding': 'packed count/coverage byte pairs in native constant-initialized arrays', 'faces': {}}
    for extent in (16, 24):
      for filename, target in [('DejaVuSansMono.ttf', 'mono'), ('DejaVuSans.ttf', 'sans')]:
        path = font_dir/filename
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        if digest != PINNED[filename]:
            raise ValueError(f'unpinned font: {filename}: {digest}')
        font = ImageFont.truetype(str(path), 14*extent//16)
        baseline = 13*extent//16
        atlas = bytearray(128*extent*extent)
        for cp in range(32, 127):
            tile = Image.new('L', (extent, extent))
            ImageDraw.Draw(tile).text((0, baseline), chr(cp), font=font, fill=255, anchor='ls')
            # Keep glyph ink inside the pre-existing UI advance; the following
            # label background must never erase the previous glyph's right edge.
            limit = advances[cp]*extent//8 if target == 'sans' else extent
            box = tile.getbbox()
            if box and box[2] > limit:
                ink = tile.crop((0, 0, box[2], extent)).resize((limit, extent), Image.Resampling.LANCZOS)
                tile = Image.new('L', (extent, extent)); tile.paste(ink, (0, 0))
            atlas[cp*extent*extent:(cp+1)*extent*extent] = tile.tobytes()
        # Keep coverage as data, rather than one machine-code store per word.
        # No new compiler feature or relaxed boot/heap boundary is required.
        encoded = bytearray()
        at = 0
        while at < len(atlas):
            end = at+1
            while end < len(atlas) and end-at < 255 and atlas[end] == atlas[at]:
                end += 1
            encoded.extend((end-at, atlas[at])); at=end
        pairs=len(encoded)//2
        encoded.extend(bytes((-len(encoded))%8))
        words=[int.from_bytes(encoded[i:i+8], 'little', signed=True) for i in range(0,len(encoded),8)]
        name=f'desktop-font-{target}{extent}'
        lines += [f'// {filename}: {len(atlas)} coverage bytes.',
                  f'var {name}-data: [Int] = ['+','.join(map(str,words))+']',
                  f'fn {name}-decode(destination: Int) -> void {{',
                  '  if destination == 0 { return }',
                  '  let pair = 0', '  let offset = 0',
                  f'  while pair < {pairs} {{',
                  f'    let word = {name}-data[pair / 4]',
                  '    let shift = (pair & 3) * 16',
                  '    let count = (word >> shift) & 255',
                  '    let coverage = (word >> (shift + 8)) & 255',
                  f'    if count == 0 || offset > {len(atlas)} - count {{ return }}',
                  '    let i = 0', '    while i < count {',
                  '      store8(destination + offset, coverage)',
                  '      offset += 1', '      i += 1', '    }',
                  '    pair += 1', '  }', '  return', '}', '']
        receipt['faces'][filename+f'/{extent}'] = {'source_sha256': digest,
            'coverage_sha256': hashlib.sha256(atlas).hexdigest(),
            'encoded_bytes':len(encoded)}
      lines += [f'fn desktop-fonts-apply{extent}(mono: Int, sans: Int) -> void {{',
                f'  desktop-font-mono{extent}-decode(mono)',
                f'  desktop-font-sans{extent}-decode(sans)', '  return', '}', '']
    lines += ['fn desktop-fonts-apply(mono: Int, sans: Int) -> void {',
              '  desktop-fonts-apply16(mono, sans)',
              '  if desktop-font-mono24 == 0 { desktop-font-mono24 = alloc(73728) }',
              '  if desktop-font-sans24 == 0 { desktop-font-sans24 = alloc(73728) }',
              '  desktop-fonts-apply24(desktop-font-mono24, desktop-font-sans24)',
              '  return', '}', '']
    return '\n'.join(lines), receipt


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font-dir', type=Path, default=ROOT/'assets/fonts/desktop')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source, receipt = generate(args.font_dir)
    files = {ROOT/'components/font-desktop-atlas.in': source,
             ROOT/'assets/fonts/desktop/receipt.json': json.dumps(receipt, indent=2)+'\n'}
    for path, content in files.items():
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f'generated asset differs: {path}')
        else:
            path.write_text(content)
    print('PASS: pinned desktop font coverage matches' if args.check else 'Generated desktop font coverage')
